/** Interview prep — read company-specific prep docs */

let selectedPrepPath = null;

async function loadInterviewPrepPanel() {
  const root = $('interviewPrepRoot');
  if (!root) return;
  root.innerHTML = '<p class="loading">Loading interview prep…</p>';

  try {
    const { files } = await api('/api/interview-prep');
    if (!selectedPrepPath && files.length) selectedPrepPath = files[0].path;

    root.innerHTML = `
      <div class="panel-intro">
        <p>Company-specific interview notes generated by your AI assistant. Read-only.</p>
      </div>
      <div class="split-2 split-2--reports">
        <section>
          <h2 class="section-title">Documents</h2>
          <nav class="report-list" id="prepListNav"></nav>
        </section>
        <section>
          <h2 class="section-title">Preview</h2>
          <div id="prepPreviewMount"></div>
        </section>
      </div>
    `;

    const nav = $('prepListNav');
    if (!files.length) {
      nav.innerHTML = '<p class="muted">No interview prep files yet. Ask your assistant: /career-ops interview-prep</p>';
      $('prepPreviewMount').innerHTML = '<div class="empty-state"><p>Nothing to show.</p></div>';
      return;
    }

    nav.innerHTML = files
      .map(
        (f) => `
      <button type="button" class="report-item${f.path === selectedPrepPath ? ' active' : ''}" data-path="${esc(f.path)}">
        <strong>${esc(f.name)}</strong>
        <span class="report-item__file">${esc(f.mtime.slice(0, 10))}</span>
      </button>`,
      )
      .join('');

    nav.querySelectorAll('.report-item').forEach((btn) => {
      btn.addEventListener('click', () => {
        selectedPrepPath = btn.dataset.path;
        loadInterviewPrepPanel();
      });
    });

    await loadPrepPreview(selectedPrepPath);
  } catch (e) {
    root.innerHTML = `<div class="empty-state"><p>${esc(e.message)}</p></div>`;
  }
}

async function loadPrepPreview(path) {
  const mount = $('prepPreviewMount');
  if (!mount || !path) return;
  mount.innerHTML = '<p class="loading">Loading…</p>';
  try {
    const { content } = await api(`/api/file?path=${encodeURIComponent(path)}`);
    mount.innerHTML = '<div id="prepMdMount"></div>';
    mountMdViewer($('prepMdMount'), content, path);
  } catch (e) {
    mount.innerHTML = `<div class="empty-state"><p>${esc(e.message)}</p></div>`;
  }
}
